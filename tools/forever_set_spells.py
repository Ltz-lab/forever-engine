"""Write src/prepare/forever_set_spells_generated.rs: the client's set bonuses (ItemSetSpell) of
every item set the item data holds, for the healer sims' set bonuses the Go reference does not
register (src/prepare/healer_gear.rs).

The tables come from wago.tools at the data's client build (data/manifest.json):

    https://wago.tools/db2/ItemSet/csv?build=<client build>
    https://wago.tools/db2/ItemSetSpell/csv?build=<client build>

A bonus whose spell the spell data does not hold is left out and counted in the file's header.

    python3 tools/forever_set_spells.py ItemSet.csv ItemSetSpell.csv
"""

import argparse
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "src" / "prepare" / "forever_set_spells_generated.rs"


def rust_string(text):
    return json.dumps(text, ensure_ascii=False)


def generate(item_sets, item_set_spells):
    build = json.loads((DATA / "manifest.json").read_text())["client_build"]
    names = {int(row["ID"]): row["Name_lang"] for row in item_sets}
    held = set()
    with open(DATA / "items.jsonl") as items:
        for line in items:
            set_id = json.loads(line).get("set_id", 0)
            if set_id:
                held.add(set_id)
    spells = set()
    with open(DATA / "spells.jsonl") as rows:
        for line in rows:
            spells.add(json.loads(line)["ID"])
    bonuses, missing = [], 0
    for row in item_set_spells:
        set_id, spell = int(row["ItemSetID"]), int(row["SpellID"])
        if set_id not in held or int(row["ChrSpecID"]) != 0:
            continue
        if spell not in spells:
            missing += 1
            continue
        bonuses.append((set_id, int(row["Threshold"]), spell))
    bonuses.sort()
    lines = [
        f"//! Generated by tools/forever_set_spells.py from client {build}'s ItemSet and",
        "//! ItemSetSpell tables: the set bonuses of every item set the item data holds, as (set,",
        f"//! pieces, bonus spell). {missing} bonuses whose spell the spell data does not hold are left",
        "//! out. Do not edit.",
        "",
        "/// (set ID, pieces, bonus spell), by set and pieces.",
        "#[rustfmt::skip]",
        "pub(crate) const SET_BONUSES: &[(i32, i32, i32)] = &[",
    ]
    lines += [f"    ({s}, {p}, {b})," for s, p, b in bonuses]
    lines += [
        "];",
        "",
        "/// The client's name of each set above, by set ID.",
        "#[rustfmt::skip]",
        "pub(crate) const SET_NAMES: &[(i32, &str)] = &[",
    ]
    lines += [f"    ({s}, {rust_string(names.get(s, ''))})," for s in sorted({b[0] for b in bonuses})]
    lines += ["];", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("item_set", type=Path, help="ItemSet.csv")
    parser.add_argument("item_set_spell", type=Path, help="ItemSetSpell.csv")
    args = parser.parse_args()
    with open(args.item_set, newline="") as a, open(args.item_set_spell, newline="") as b:
        OUT.write_text(generate(list(csv.DictReader(a)), list(csv.DictReader(b))))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
